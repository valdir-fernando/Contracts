const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
    const base = process.env.CONTRACTS_URL || 'http://127.0.0.1:8000';
    const manifest = JSON.parse(fs.readFileSync('/tmp/manifest.json', 'utf8'));
    const browser = await chromium.launch({ headless: true });
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const html = `<!doctype html><html><head><link rel="stylesheet" href="${base}/build/${manifest['resources/css/app.css'].file}"></head><body><main><table class="data-table"><tbody><tr data-row-href="/row-item"><td><a href="/row-item" id="primary">Item 1</a></td><td id="cell">Dados do item</td><td><a href="/row-action" id="action">Outra ação</a><button id="button" type="button" onclick="this.dataset.clicked='yes'">Botão</button><input id="field"></td></tr><tr><td id="inactive">Item sem destino</td></tr></tbody></table></main><script type="module" src="${base}/build/${manifest['resources/js/app.js'].file}"></script></body></html>`;
    await context.route('**/row-fixture', route => route.fulfill({ contentType: 'text/html', body: html }));
    await context.route('**/row-item', route => route.fulfill({ contentType: 'text/html', body: '<h1>Dados do item 1</h1>' }));
    await context.route('**/row-action', route => route.fulfill({ contentType: 'text/html', body: '<h1>Ação independente</h1>' }));
    const open = async () => { await page.goto(base + '/row-fixture'); await page.waitForLoadState('networkidle'); };
    await open();
    await page.locator('#cell').click();
    await page.waitForURL('**/row-item');
    await open();
    await page.locator('#primary').focus();
    await page.keyboard.press('Enter');
    await page.waitForURL('**/row-item');
    await open();
    await page.locator('#button').click();
    assert.equal(await page.locator('#button').getAttribute('data-clicked'), 'yes');
    await page.locator('#field').fill('Texto preservado');
    await page.locator('#inactive').click();
    assert.equal(page.url(), base + '/row-fixture');
    await page.evaluate(() => {
        const cell = document.querySelector('#cell');
        const range = document.createRange(); range.selectNodeContents(cell);
        window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
        cell.dispatchEvent(new MouseEvent('click', { bubbles: true, button: 0 }));
    });
    assert.equal(page.url(), base + '/row-fixture');
    await page.evaluate(() => window.getSelection().removeAllRanges());
    await page.locator('#action').click();
    await page.waitForURL('**/row-action');
    await open();
    const popupPromise = context.waitForEvent('page');
    await page.locator('#cell').click({ modifiers: ['Control'] });
    const popup = await popupPromise;
    await popup.waitForURL('**/row-item');
    assert.equal(page.url(), base + '/row-fixture');
    await popup.close();
    await page.evaluate(() => {
        const row = document.createElement('tr'); row.dataset.rowHref = '/row-item'; row.innerHTML = '<td id="dynamic">Novo item</td>';
        document.querySelector('tbody').append(row);
    });
    await page.locator('#dynamic').click();
    await page.waitForURL('**/row-item');
    assert.deepEqual(errors, []);
    console.log('Rows navigate correctly; keyboard, controls, text selection, new tabs and dynamically inserted rows verified.');
    await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
